CREATE TABLE IF NOT EXISTS events (id TEXT PRIMARY KEY, kind TEXT NOT NULL, source TEXT NOT NULL, volume_ml REAL, received_at REAL NOT NULL);
CREATE TABLE IF NOT EXISTS reminders (id INTEGER PRIMARY KEY CHECK (id=1), interval_minutes INTEGER NOT NULL, next_due REAL NOT NULL);
CREATE TABLE IF NOT EXISTS notifications (id INTEGER PRIMARY KEY AUTOINCREMENT, reminder_due REAL NOT NULL UNIQUE, provider TEXT NOT NULL, created_at REAL NOT NULL);
